const AUTHOR_ID = 'user-dapur'

function makeRecipe(seed: RecipeSeed): Recipe {
  return {
    id: `recipe-${seed.slug}`,
    slug: seed.slug,
    title: seed.title,
    excerpt: seed.excerpt,
    story: seed.story,
    categoryId: `category-${seed.category}`,
    authorId: AUTHOR_ID,
    image: `/media/recipes/${seed.slug}.webp`,
    prepMinutes: seed.prepMinutes,
    cookMinutes: seed.cookMinutes,
    servings: seed.servings,
    difficulty: seed.difficulty,
    ingredients: seed.ingredients,
    steps: seed.steps,
    status: 'active',
    popularity: seed.popularity,
    publishedAt: seed.publishedAt,
  }
}

